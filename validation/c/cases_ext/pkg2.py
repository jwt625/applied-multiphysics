"""Class-c cases of the advanced packaging examples, part 2 (lane G6, DevLog-063): ids PK-07..PK-19.

Each case runs a sims/<id>.yaml on the engine and compares evaluation items of the sim (extract kind 'result') with
references generated by validation/pkg2/<script>.py into eval/expected/PK-xx.json. Loaded by validation/c/build_cases.py
(CASES list); rebuild with `cd validation && uv run python c/build_cases.py` (delete eval/cases/c/PK-xx.yaml first, the
builder skips existing files without --force).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[3]
EXP = ROOT / "eval" / "expected"
CREATED = "2026-11-18"
NO_HERO = {"suitable": False, "why": "verification case, not a demo"}
OWN = {"source_license": "own derivation, own reference code and closed forms from cited literature (formulas only); "
                         "GPL-3.0-or-later code",
       "allowed": ["cite_values", "re_derive_setup"], "forbidden": ["copy_text", "copy_figures"]}


def _exp(cid: str) -> dict:
    return json.loads((EXP / f"{cid}.json").read_text())


def _prov(cid: str, citation: str, locator: str) -> dict:
    return {"citation": citation, "locator": locator, "accessed": None, "generator": _exp(cid)["generator"],
            "source_accessed": CREATED}


def tref(cid: str, mid: str, node: str, tol: dict, *, citation: str, locator: str, gate: bool = True,
         note: str | None = None, quantity: str | None = None, tid: str | None = None, spec: Any = None,
         form: str = "closed_form") -> dict[str, Any]:
    e = _exp(cid)
    t = next(x for x in e["targets"] if x["metric_id"] == mid)
    r: dict[str, Any] = {**({"id": tid} if tid else {}),
        "quantity": quantity or t.get("definition", mid),
        "metric_id": mid,
        "value": t["value"],
        "unit": t["unit"],
        "tolerance": tol,
        "bounds": None,
        "basis": "D",
        "form": form,
        "gate": gate,
        "expected": {"file": f"eval/expected/{cid}.json", "metric_id": mid},
        "provenance": _prov(cid, citation, locator),
        "extract": {"kind": "result", "node": node},
        **({"spec": spec} if spec is not None else {}),
    }
    if note:
        r["note"] = note
    return r


def case(cid: str, title: str, physics: list, dim: Any, refs: list, *, sim: str, conv: dict, budget: float | None,
         geometry: dict, materials: dict, bcs: list, study: dict, assumptions: list, notes: list,
         missing: list | None = None) -> dict:
    return {
        "schema": "amp-eval/0", "id": cid, "class": "c", "title": title, "status": "unvalidated",
        "untestable_reason": None, "physics": physics, "dimension": dim, "units": "SI",
        "geometry": geometry, "materials": materials, "bcs": bcs, "initial": None, "study": study,
        "references": refs, "reference_results": [], "convergence": conv,
        "speed": {"budget_s": {"browser": budget, "native": None},
                  "budget_basis": "est. from the lane's own runs on 2026-11-18 (DevLog-063), not a browser measurement",
                  "report": ["dofs", "wall_s_by_stage", "iterations", "error_vs_ref"], "reference_timings": []},
        "dataset": None, "rights": OWN, "hero": NO_HERO, "spec": sim, "missing": missing or [],
        "assumptions": assumptions, "notes": notes, "lane": "G6", "created": CREATED,
    }


